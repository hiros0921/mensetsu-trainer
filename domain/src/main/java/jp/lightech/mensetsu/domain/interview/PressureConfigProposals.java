package jp.lightech.mensetsu.domain.interview;

/**
 * 圧の設定の案（第7段階）。
 *
 * <h2>【重要】いずれも採用されていません</h2>
 *
 * 仕様書7章は「スコアリングの重み・5段階の閾値を、AIが独自に決定しないこと」としている。
 * 圧のパラメータはスコアではないが、面接の進行そのものを決めてしまう。第5段階と同じ扱いにする。
 *
 * <h2>第3段階の暫定値の何が問題か</h2>
 *
 * 第6段階の実測で、具体的に答えると圧が 20 → 0 → 2 と底に張り付いた。
 * 圧迫面接（初期値55）でも、具体的に答えると3往復で0になり、そこから何をしても動かない。
 * 逆に曖昧だと1往復で強制遷移の境目に届く。
 *
 * <p>1往復の振れ幅（±16〜20）が、100のスケールに対して大きすぎる。
 * 圧が「状態」ではなく「直前の1回の判定」になっている。
 *
 * <h2>3案の違い</h2>
 *
 * <pre>
 *   案P1  幅を半分に。ゆっくり動く。持ち直しも崩れも数往復かかる
 *   案P2  下げにくくする。一度上がった空気は簡単には戻らない
 *   案P3  上がりやすく戻りにくい。圧迫面接らしさを強く出す
 * </pre>
 */
public final class PressureConfigProposals {

  private PressureConfigProposals() {}

  /**
   * 案P1「幅を半分に」。
   *
   * <p>暫定値の幅をおおよそ半分にした。1往復の振れが小さいので、圧が「直前の1回」ではなく
   * 「ここまでの流れ」を表すようになる。
   *
   * <p>その代わり、圧迫面接に入るまでに時間がかかる。PROBE の上限（3往復）で
   * PRESSURE に入れない可能性がある。
   */
  public static PressureConfig p1() {
    return new PressureConfig(6, 4, 11, 3, 2, 3, 75, 95);
  }

  /**
   * 案P2「下げにくくする」。
   *
   * <p>上げ幅は暫定値のまま、下げ幅を小さくした。一度上がった空気は、
   * 一言では元に戻らない。取り返すには何度か続ける必要がある。
   *
   * <p>底に張り付きにくくなるが、上がるのは速いままなので、
   * 曖昧な回答が1〜2回続くと強制遷移まで届く。
   */
  public static PressureConfig p2() {
    return new PressureConfig(12, 8, 22, 3, 2, 3, 75, 95);
  }

  /**
   * 案P3「上がりやすく戻りにくく」。
   *
   * <p>下げ幅を小さくしたうえで、強制遷移の境目も下げた。圧迫面接に入りやすい。
   * 圧迫面接モードの主眼が「圧に耐える練習」なら、PRESSURE フェーズに入らないと
   * 練習にならない、という立場。
   *
   * <p>厳しく感じるはず。練習として続けられるかは、実際に受けてみないと分からない。
   */
  public static PressureConfig p3() {
    return new PressureConfig(14, 9, 24, 2, 2, 2, 65, 92);
  }
}
