package jp.lightech.mensetsu.domain.interview;

/**
 * モードごとの圧の設定。
 *
 * <h2>採用（第7段階）</h2>
 *
 * 諏訪さんが案P2（下げにくくする）を選ばれた。理由:
 *
 * <blockquote>案P1は落とす。「具体→曖昧（崩れる）」で耐え切ってしまうから。これは圧迫面接が
 * まさに測りたい失敗。最初は良いことを言うのに、押されると崩れる人。ここを見逃す設定は採れない。
 *
 * <p>案P3も落とす。底に着かない、つまりどれだけ良い回答をしても報われない。
 * 練習アプリとして続かない。
 *
 * <p>案P2の「一度上がった空気は戻りにくい」という思想は、実際の面接官の心理として正しい。
 * 一度あやしいと思われたら、後の良い回答では完全に戻らない。交互で押し切られるのも妥当。
 * ムラがあれば突かれるので。</blockquote>
 *
 * <h2>【重要】全モードに同じ設定を使っています</h2>
 *
 * 諏訪さんが判断されたのは圧迫面接モードについて。エンジニア面接と英語面接にも同じ設定を
 * 当てているのは、こちらの判断です。理由は2つ。
 *
 * <ul>
 *   <li>「一度上がった空気は戻りにくい」は面接官の心理の話で、モードに固有ではない
 *   <li>第3段階の暫定値のままにすると、エンジニア面接でも圧が3往復で底に着き、
 *       表情が動かなくなる（実測: 20→4→0）
 * </ul>
 *
 * <p>モードごとに変えたい場合は、ここを分ければよい。分ける必要が出るまでは1つにしておく。
 */
public final class PressureConfigs {

  private PressureConfigs() {}

  /**
   * 採用された圧の設定（案P2）。
   *
   * <p>上げ幅は暫定値のまま、下げ幅を半分にした。
   *
   * <pre>
   *   上げ  曖昧+12  主語なし+8  無言+22
   *   下げ  数字-3   固有名詞-2  自分-3
   *   強制遷移 75 ／ 押し切られ 95
   * </pre>
   */
  public static PressureConfig adopted() {
    return new PressureConfig(12, 8, 22, 3, 2, 3, 75, 95);
  }

  /** モードごとの設定。今はどのモードも同じものを返す。 */
  public static PressureConfig forMode(Mode mode) {
    return adopted();
  }
}
