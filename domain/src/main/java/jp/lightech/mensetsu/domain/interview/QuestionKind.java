package jp.lightech.mensetsu.domain.interview;

/**
 * 面接官の発言の種類。
 *
 * <p>分ける理由は速度（第1段階 Q5）。面接官の発話は、実は2種類ある。
 *
 * <ul>
 *   <li>相槌・つなぎ（「なるほど」「もう少し詳しく教えてください」）— 質は要らない
 *   <li>深掘りの質問・矛盾の指摘 — 質が要る
 * </ul>
 *
 * <p>前者は LLM を呼ばずに、回答を受け取った瞬間に返す。実際の面接官も、次を
 * 考えている間はこれをやっている。後者をその裏で作れば、待ち時間が「間」として
 * 自然に見える。
 *
 * <p>質を落として速くするのではない。遅さを設計で吸収する。
 */
public enum QuestionKind {
  /** アプリ側の定型。LLM を呼ばない。即座に返る。 */
  CANNED,
  /** LLM が作る。深掘り・矛盾の指摘。 */
  GENERATED
}
