package jp.lightech.mensetsu.domain.scoring;

/**
 * 測れなかった軸をどう扱うか。
 *
 * <h2>これは判断であって、実装の都合ではありません</h2>
 *
 * 技術用語を一度も口にしなかった面接では、深さが測れない。ここをどう扱うかで、
 * その人の判定が大きく変わる。
 *
 * <p>どちらが正しいとは言えない。面接の目的による。だから私は決めない。
 */
public enum UnmeasuredHandling {

  /**
   * 測れた軸だけで100点満点にする（重みを配り直す）。
   *
   * <p><b>この立場</b>: 聞かれなかったことで減点しない。面接の運を実力から切り離す。
   *
   * <p><b>起きること</b>: 技術の話を一切しなくても、他の軸が良ければ高い判定が出る。
   * 深さは「掘られて答えられたか」を測る軸なので、掘られなければ問われない。
   */
  REDISTRIBUTE("測れた軸だけで100点満点にする"),

  /**
   * 測れなかった軸を0点として扱う。
   *
   * <p><b>この立場</b>: 掘られる材料を自分から出せなかったことも、面接の結果のうち。
   * 技術面接で技術の話が出てこなかったなら、それ自体が評価される。
   *
   * <p><b>起きること</b>: 深さが測れないだけで最大35点（案Aの場合）を失う。
   * 相手が技術の話を振らなかった回でも、同じ減点になる。
   */
  ZERO("測れなかった軸は0点として数える");

  private final String label;

  UnmeasuredHandling(String label) {
    this.label = label;
  }

  public String label() {
    return label;
  }
}
